#!/usr/bin/env python3
"""Join per-page OCR text into one markdown file per unit.

Reads library/sources/<id>/structure.json and library/sources/<id>/text/,
writes library/sources/<id>/units/. Output is derived and safe to delete.

Usage:
    python3 tools/build_units.py --source-id lawyers-english-language-coursebook
"""
import argparse
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source-id", required=True)
    args = ap.parse_args()

    src = os.path.join(ROOT, "library", "sources", args.source_id)
    structure = json.load(open(os.path.join(src, "structure.json")))
    meta = json.load(open(os.path.join(src, "metadata.json")))
    text_dir = os.path.join(src, "text")
    unit_dir = os.path.join(src, "units")
    os.makedirs(unit_dir, exist_ok=True)

    written = []
    for unit in structure["units"]:
        held = unit.get("held_pages")
        if not held:
            continue
        first, last = held
        name = "-".join(x for x in [unit["key"].lower(), slug(unit["title"])] if x)
        if unit["key"].lower() == slug(unit["title"]):
            name = unit["key"].lower()
        dest = os.path.join(unit_dir, name + ".md")

        head = ["# %s%s" % (
            ("Unit %s — " % unit["unit"]) if unit["unit"] else "", unit["title"])]
        if unit["toles_level"]:
            head.append("")
            head.append("TOLES level: %s" % unit["toles_level"])
        head.append("")
        head.append("Source: %s (%s, %s). Printed pages %d–%d%s." % (
            meta["title"], meta["publisher"], meta["year"], first, last,
            "" if unit["status"] == "held" else " — unit is incomplete in the library"))
        head.append("")
        head.append("Raw OCR text, not proof-read.")
        head.append("")
        head.append("")

        body = []
        for page in range(first, last + 1):
            path = os.path.join(text_dir, "page-%03d.txt" % page)
            if not os.path.exists(path):
                continue
            content = open(path).read().strip()
            body.append("---\n\n## page %d\n" % page)
            body.append(content if content else "*(no text recognised on this page)*")
            body.append("")
        with open(dest, "w") as fh:
            fh.write("\n".join(head) + "\n".join(body) + "\n")
        written.append((name, first, last, unit["status"]))
        print("%-42s pp. %3d-%3d  %s" % (name, first, last, unit["status"]))

    index = os.path.join(unit_dir, "README.md")
    with open(index, "w") as fh:
        fh.write("# Units held\n\nGenerated by `tools/build_units.py` from `../text/`.\n\n")
        fh.write("| Unit | Pages | Status |\n| --- | --- | --- |\n")
        for name, first, last, status in written:
            fh.write("| [%s](%s.md) | %d–%d | %s |\n" % (name, name, first, last, status))
    print("index ->", index)


if __name__ == "__main__":
    main()
